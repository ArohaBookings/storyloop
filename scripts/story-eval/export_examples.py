#!/usr/bin/env python3
"""
Publish real drafts from a scored story-eval run as site examples.

    python3 scripts/story-eval/export_examples.py --run .test-local/story-eval/baseline

Writes lib/real-examples.ts. Every example on the site is a draft the
production pipeline actually wrote for that note, copied without a word
changed, together with the evidence it cited, what it flagged for the educator
to check, and the independent judge's fidelity score. Only drafts with no hard
failures and no invented speech are eligible; the list below picks the ones
that show the range (every age group, both countries, sparse and rich notes, a
group moment, a privacy flag).
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent

# (case id, rep, setting shown on the page)
PICKS = [
    ("infant-tummy-time-nz", 0, "Infant room, tummy time"),
    ("one-feeding-au", 0, "Toddler room, morning tea"),
    ("toddler-sand-quote-nz", 1, "Sandpit and water trough"),
    ("two-shoes-independence-nz", 1, "Getting ready for outside"),
    ("two-painting-colours-au", 0, "Easel painting"),
    ("three-waiata-nz", 0, "Mat time waiata"),
    ("three-teeth-nz", 0, "Kai time, a new baby at home"),
    ("four-long-rich-au", 0, "Marble run, a long note"),
    ("four-group-names-nz", 1, "Three children, one hut"),
    ("four-writing-name-au", 0, "A three-line note"),
    ("four-maths-au", 0, "Sorting and counting"),
    ("four-sensitive-family-au", 1, "A hard week at home"),
]

AGE_LABEL = {
    "0-12 months": "Under 1",
    "1-2 years": "1 to 2 years",
    "2-3 years": "2 to 3 years",
    "3-4 years": "3 to 4 years",
    "4-5 years": "4 to 5 years",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", required=True)
    args = parser.parse_args()
    run = Path(args.run)
    raw = {(i["id"], i["rep"]): i for i in json.loads((run / "raw.json").read_text())["results"]}
    scored = {(r["id"], r["rep"]): r for r in json.loads((run / "scored.json").read_text())["rows"]}
    cases = {c["id"]: c for c in json.loads((HERE / "cases.json").read_text())}
    generated_at = json.loads((run / "raw.json").read_text())["generatedAt"][:10]

    examples = []
    for case_id, rep, setting in PICKS:
        item, row, case = raw[(case_id, rep)], scored[(case_id, rep)], cases[case_id]
        if row["check"]["issues"]:
            raise SystemExit("%s#%d has hard failures; pick another" % (case_id, rep))
        if (row.get("judge") or {}).get("invented_speech"):
            raise SystemExit("%s#%d has judged invented speech; pick another" % (case_id, rep))
        result = item["result"]
        examples.append({
            "slug": case_id,
            "childName": case.get("childName") or "",
            "age": AGE_LABEL.get(case["ageGroup"], case["ageGroup"]),
            "framework": case["framework"],
            "setting": setting,
            "note": case["observations"],
            "title": result.get("storyTitle") or "",
            "story": result["story"],
            "fromNote": [a for a in (result.get("evidenceAnchors") or []) if isinstance(a, str)][:5],
            "toCheck": ([c for c in (result.get("educatorChecks") or []) if isinstance(c, str)][:3]
                        + [a for a in (result.get("assumptions") or []) if isinstance(a, str)][:2]),
            "privacy": [i.get("label") for i in (result.get("privacyGuardian") or {}).get("issues") or []],
            "fidelity": (row.get("judge") or {}).get("fidelity"),
            "words": row["check"]["words"],
        })

    body = json.dumps(examples, indent=2, ensure_ascii=False)
    out = REPO / "lib" / "real-examples.ts"
    out.write_text(
        "// GENERATED by scripts/story-eval/export_examples.py from the story evaluation\n"
        "// run of %s. Do not edit by hand: every draft here is exactly what the\n"
        "// production pipeline wrote for the note beside it.\n\n"
        "export type RealExample = {\n"
        "  slug: string;\n  childName: string;\n  age: string;\n  framework: \"AU\" | \"NZ\";\n  setting: string;\n"
        "  note: string;\n  title: string;\n  story: string;\n  fromNote: string[];\n  toCheck: string[];\n"
        "  privacy: string[];\n  fidelity: number | null;\n  words: number;\n};\n\n"
        "export const REAL_EXAMPLES_DATE = %s;\n\n"
        "export const REAL_EXAMPLES: RealExample[] = %s;\n" % (generated_at, json.dumps(generated_at), body),
        encoding="utf-8",
    )
    print("wrote", out.relative_to(REPO), len(examples), "examples")
    export_report(run, raw, scored, cases, generated_at)


def export_report(run, raw, scored, cases, generated_at):
    """lib/accuracy-report.ts: the numbers behind /accuracy, from the same run."""
    summary = json.loads((run / "scored.json").read_text())["summary"]
    rows = [r for r in scored.values() if "check" in r]
    by_age = {}
    for r in rows:
        age = AGE_LABEL.get(cases[r["id"]]["ageGroup"], cases[r["id"]]["ageGroup"])
        bucket = by_age.setdefault(age, {"drafts": 0, "fidelity": []})
        bucket["drafts"] += 1
        if isinstance((r.get("judge") or {}).get("fidelity"), (int, float)):
            bucket["fidelity"].append(r["judge"]["fidelity"])
    ages = [
        {"age": age, "drafts": v["drafts"], "fidelity": round(sum(v["fidelity"]) / len(v["fidelity"]), 1) if v["fidelity"] else None}
        for age, v in sorted(by_age.items(), key=lambda kv: list(AGE_LABEL.values()).index(kv[0]) if kv[0] in AGE_LABEL.values() else 99)
    ]
    # A few of the reviewer's most typical findings, verbatim, so the page shows
    # what "interpretation stated as fact" actually looks like.
    samples = []
    for r in rows:
        for item in (r.get("judge") or {}).get("invented_events") or []:
            if 20 < len(item) < 90 and len(samples) < 4:
                samples.append(item)
    report = {
        "date": generated_at,
        "notes": len({r["id"] for r in rows}),
        "drafts": summary["drafts"],
        "wordsInChildMouth": summary["invented_speech_deterministic"],
        "frameworkMixups": summary["framework_leaks"],
        "missingSections": summary["missing_section_drafts"],
        "fidelity": summary["fidelity"],
        "usefulness": summary["usefulness"],
        "readsNaturally": summary["reads_naturally"],
        "interpretationsAsFact": summary["judge_invented_events"],
        "feelingsAsFact": summary["judge_invented_feelings"],
        "medianWords": summary["median_words"],
        "medianSeconds": summary["median_seconds"],
        "byAge": ages,
        "reviewerSamples": samples,
        "cases": [{"age": AGE_LABEL.get(c["ageGroup"], c["ageGroup"]), "framework": c["framework"], "tests": c.get("notes", "")} for c in cases.values()],
    }
    out = REPO / "lib" / "accuracy-report.ts"
    out.write_text(
        "// GENERATED by scripts/story-eval/export_examples.py. The numbers on /accuracy,\n"
        "// from the story evaluation run of %s. Do not edit by hand.\n\n"
        "export const ACCURACY_REPORT = %s as const;\n" % (generated_at, json.dumps(report, indent=2, ensure_ascii=False)),
        encoding="utf-8",
    )
    print("wrote", out.relative_to(REPO))


if __name__ == "__main__":
    main()
